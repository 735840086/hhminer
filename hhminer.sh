# ===================== 原版安装/更新/卸载逻辑（增强） =====================
install_hhminer() {
    check_os
    detect_system
    check_dependencies
    # 安装wget
    case $os in
        'ubuntu'|'debian')
            apt-get -y update >/dev/null 2>&1
            apt-get -y install wget git >/dev/null 2>&1
            ;;
        'centos')
            yum install -y wget git >/dev/null 2>&1
            ;;
    esac
    # 检测运行中程序，停止后安装
    if check_process; then
        echo -e "[${yellow}提示${plain}] 检测到hhminer正在运行，必须停止才能更新/重装"
        echo "1. 停止程序并继续安装"
        echo "2. 取消安装"
        read -p "请选择: " choose
        case $choose in
        1) stop ;;
        2) echo -e "[${yellow}提示${plain}] 安装取消"; return ;;
        *) echo -e "[${red}错误${plain}] 输入无效，取消安装"; return ;;
        esac
    fi
    disable_firewall
    apply_global_network_optimization
    # 清理更新目录
    if [ -d ${updatePath} ]; then
        rm -rf ${updatePath}
    fi
    mkdir -p ${updatePath}
    cd ${updatePath}
    # 下载主程序
    wget --no-check-certificate https://raw.githubusercontent.com/735840086/hhminer/main/hhminer -O hhminer
    if [ $? -ne 0 ]; then
        echo -e "[${red}错误${plain}] 主程序下载失败"
        exit -1;
    fi
    chmod +x hhminer
    # 下载版本文件
    wget --no-check-certificate https://raw.githubusercontent.com/735840086/hhminer/main/version -O version
    if [ $? -ne 0 ]; then
        echo -e "[${red}错误${plain}] version文件下载失败"
        exit -1;
    fi
    # 备份旧程序
    if [ -f "${installPath}/hhminer.bak" ]; then
        rm -rf "${installPath}/hhminer.bak"
        rm -rf "${installPath}/version.bak"
    fi
    if [ -f "${installPath}/hhminer" ]; then
        mv "${installPath}/hhminer" "${installPath}/hhminer.bak"
        mv "${installPath}/version" "${installPath}/version.bak"
    fi
    # 移动新文件到安装目录
    mv "${updatePath}/hhminer" "${installPath}/hhminer"
    mv "${updatePath}/version" "${installPath}/version"
    # 自动生成随机端口（无配置时）
    if [ ! -f "$PATH_CONFIG" ]; then
        default_port=$(generate_port)
        setConfig START_PORT "$default_port"
    fi
    # 创建服务并启动
    create_service
    start
}

update_hhminer() {
    if [ -d ${updatePath} ]; then
        rm -rf ${updatePath}
    fi
    mkdir -p ${updatePath}
    cd ${updatePath}
    wget --no-check-certificate https://raw.githubusercontent.com/735840086/hhminer/main/version -O version
    if [ $? -ne 0 ]; then
        echo -e "[${red}错误${plain}] 获取版本文件失败"
        exit -1;
    fi
    newVersion=$(cat ${updatePath}/version)
    oldVerion=$(cat ${installPath}/version 2>/dev/null || echo "0")
    if [ "${newVersion}" == "${oldVerion}" ]; then
        echo -e "[${green}提示${plain}] 当前已是最新版本，无需更新"
        exit 0
    fi
    echo -e "[${yellow}更新${plain}] 检测到新版本:$newVersion，开始更新"
    install_hhminer
}

