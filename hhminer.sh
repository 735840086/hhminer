# ===================== CLI命令行工具安装/卸载 =====================
ensure_cli_dependencies() {
    local missing=""
    local cmd
    for cmd in cat grep readlink; do
        if ! command -v "$cmd" >/dev/null 2>&1; then
            missing="${missing} ${cmd}"
        fi
    done
    if [ -n "$missing" ]; then
        echo -e "[${red}错误${plain}] CLI依赖缺失:$missing"
        return 1
    fi
}

is_hhminer_installed() {
    [ -x "${installPath}/${serviceName}" ]
}

is_cli_managed_command() {
    [ -L "$CLI_LINK_PATH" ] && readlink "$CLI_LINK_PATH" | grep -q "$PATH_CLI" || grep -q "$CLI_LAUNCHER_MARKER" "$CLI_LINK_PATH" 2>/dev/null
}

is_cli_installed() {
    [ -x "$PATH_CLI" ] && is_cli_managed_command
}

check_cli_command_conflict() {
    local existing_command
    existing_command=$(command -v "$CLI_COMMAND_NAME" 2>/dev/null || true)
    if [ -n "$existing_command" ]; then
        if [ "$existing_command" = "$CLI_LINK_PATH" ] && is_cli_managed_command; then
            return 0
        fi
        echo -e "[${red}错误${plain}] $CLI_COMMAND_NAME 命令已存在，非本脚本管理，冲突"
        return 1
    fi
    if [ -e "$CLI_LINK_PATH" ] || [ -L "$CLI_LINK_PATH" ]; then
        if is_cli_managed_command; then
            return 0
        fi
        echo -e "[${red}错误${plain}] $CLI_LINK_PATH 文件存在，冲突"
        return 1
    fi
}

create_cli_launcher() {
    mkdir -p /usr/local/bin
    [ -L "$CLI_LINK_PATH" ] && rm -f -- "$CLI_LINK_PATH"
    cat > "$CLI_LINK_PATH" <<EOF
#!/bin/sh
# ${CLI_LAUNCHER_MARKER}
APP_DIR="$installPath"
APP_EXEC="$serviceName"
CLI_EXEC="$CLI_EXEC_NAME"
SERVICE_NAME="$serviceName"
APP_PATH="\${APP_DIR}/\${APP_EXEC}"
CLI_PATH="\${APP_DIR}/\${CLI_EXEC}"
CONFIG_FILE="\${APP_DIR}/$CONFIG_FILE_NAME"
NOHUP_FILE="\${APP_DIR}/nohup.out"
ERR_FILE="\${APP_DIR}/err.log"
SERVICE_FILE="/lib/systemd/system/\${SERVICE_NAME}.service"
show_usage() {
    echo "用法: hhminerctl [start|stop|restart|help]"
}
require_root() {
    if [ "\$(id -u)" != "0" ]; then
        echo "请使用root用户执行"
        exit 1
    fi
}
is_systemd_available() {
    command -v systemctl >/dev/null 2>&1 && [ -d /run/systemd/system ]
}
is_running() {
    pgrep -x "\$APP_EXEC" >/dev/null 2>&1
}
ensure_app_exists() {
    if [ ! -x "\$APP_PATH" ]; then
        echo "未安装hhminer，请先执行脚本安装"
        return 1
    fi
}
open_cli() {
    if [ ! -x "\$CLI_PATH" ]; then
        echo "CLI工具未安装，请通过脚本菜单安装"
        exit 1
    fi
    web_ui=\$(sed -n 's/^[[:space:]]*ENABLE_WEB_UI[[:space:]]*=[[:space:]]*\([^[:space:]]*\).*$/\1/p' "\$CONFIG_FILE" 2>/dev/null | tail -n 1)
    if [ "\$web_ui" != "0" ]; then
        echo "CLI工具仅在WEB面板关闭后可用，请先关闭WEB访问"
        exit 1
    fi
    cd "\$APP_DIR" || exit 1
    exec "\$CLI_PATH"
}
start_app() {
    require_root
    ensure_app_exists || return 1
    if is_running; then
        echo "hhminer已运行"
        return 0
    fi
    if is_systemd_available && [ -f "\$SERVICE_FILE" ]; then
        systemctl start "\${SERVICE_NAME}.service"
    else
        mkdir -p "\$APP_DIR"
        touch "\$NOHUP_FILE" "\$ERR_FILE"
        chmod 640 "\$NOHUP_FILE" "\$ERR_FILE" 2>/dev/null || true
        nohup "\$APP_PATH" >> "\$NOHUP_FILE" 2>> "\$ERR_FILE" &
    fi
    i=0
    while [ "\$i" -lt 10 ]; do
        if is_running; then
            echo "hhminer启动成功"
            return 0
        fi
        sleep 1
        i=\$((i + 1))
    done
    echo "hhminer启动失败"
    return 1
}
stop_app() {
    require_root
    was_running=0
    if is_running; then
        was_running=1
    fi
    if is_systemd_available && [ -f "\$SERVICE_FILE" ]; then
        systemctl stop "\${SERVICE_NAME}.service"
    fi
    if is_running; then
        pids=\$(pgrep -x "\$APP_EXEC")
        for pid in \$pids; do
            kill -TERM "\$pid"
        done
    fi
    i=0
    while [ "\$i" -lt 10 ]; do
        if ! is_running; then
            if [ "\$was_running" = "1" ]; then
                echo "hhminer已停止"
            else
                echo "hhminer未运行"
            fi
            return 0
        fi
        sleep 1
        i=\$((i + 1))
    done
    echo "停止超时"
    return 1
}
restart_app() {
    stop_app || return 1
    start_app
}
if [ "\$#" -eq 0 ]; then
    open_cli
fi
case "\$1" in
start) start_app ;;
stop) stop_app ;;
restart) restart_app ;;
help|--help|-h) show_usage ;;
*) echo "未知命令: \$1"; show_usage; exit 1 ;;
esac
EOF
    chmod 755 "$CLI_LINK_PATH"
}

