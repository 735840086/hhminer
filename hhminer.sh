# ===================== 防火墙关闭 =====================
disable_firewall() {
    local os_name="${OS_ID:-unknown}"
    echo -e "[${yellow}操作${plain}] 尝试关闭系统防火墙"
    if [ "$os_name" == "ubuntu" ] && command -v ufw >/dev/null 2>&1; then
        ufw disable
        echo -e "[${green}成功${plain}] Ubuntu ufw防火墙已关闭"
    elif [[ "$os_name" =~ ^(centos|rhel|rocky|almalinux|fedora)$ ]] && is_systemd_available; then
        systemctl stop firewalld
        systemctl disable firewalld
        echo -e "[${green}成功${plain}] CentOS firewalld防火墙已关闭"
    else
        echo -e "[${yellow}提示${plain}] 未知系统，自动关闭防火墙失败，请手动放行端口"
    fi
}

# ===================== 进程启停等待工具 =====================
check_process() {
    pgrep -x "$serviceName" >/dev/null 2>&1
}

is_fast_process_wait_supported() {
    if [ -n "$PROCESS_WAIT_INTERVAL_SUPPORTED" ]; then
        [ "$PROCESS_WAIT_INTERVAL_SUPPORTED" = "1" ]
        return
    fi
    if sleep "$PROCESS_WAIT_INTERVAL" 2>/dev/null; then
        PROCESS_WAIT_INTERVAL_SUPPORTED="1"
        return 0
    fi
    PROCESS_WAIT_INTERVAL_SUPPORTED="0"
    return 1
}

wait_for_process_started() {
    local timeout="${2:-10}"
    local interval="1"
    local max_attempts="$timeout"
    local attempts=0
    if check_process; then
        return 0
    fi
    if is_fast_process_wait_supported; then
        interval="$PROCESS_WAIT_INTERVAL"
        max_attempts=$((timeout * PROCESS_WAIT_STEPS_PER_SECOND))
    fi
    while [ "$attempts" -lt "$max_attempts" ]; do
        if check_process; then
            return 0
        fi
        sleep "$interval"
        attempts=$((attempts + 1))
    done
    return 1
}

wait_for_process_stopped() {
    local timeout="${2:-10}"
    local interval="1"
    local max_attempts="$timeout"
    local attempts=0
    if ! check_process; then
        return 0
    fi
    if is_fast_process_wait_supported; then
        interval="$PROCESS_WAIT_INTERVAL"
        max_attempts=$((timeout * PROCESS_WAIT_STEPS_PER_SECOND))
    fi
    while [ "$attempts" -lt "$max_attempts" ]; do
        if ! check_process; then
            return 0
        fi
        sleep "$interval"
        attempts=$((attempts + 1))
    done
    return 1
}

kill_process() {
    local pids=($(pgrep -x "$serviceName"))
    if [ ${#pids[@]} -eq 0 ]; then
        echo -e "[${yellow}提示${plain}] 未检测到$serviceName进程"
        return 1
    fi
    for pid in "${pids[@]}"; do
        echo -e "[${yellow}停止${plain}] 终止进程PID:$pid"
        kill -TERM "$pid"
    done
    if wait_for_process_stopped 10; then
        echo -e "[${green}成功${plain}] 进程全部终止"
    else
        echo -e "[${red}错误${plain}] 进程停止超时，强制kill"
        for pid in "${pids[@]}"; do kill -9 $pid; done
    fi
}

# ===================== 运行目录初始化 =====================
ensure_runtime_files() {
    mkdir -p "$installPath"
    chmod 755 "$installPath"
    [ -f "$PATH_NOHUP" ] || touch "$PATH_NOHUP"
    [ -f "$PATH_ERR" ] || touch "$PATH_ERR"
    chmod 640 "$PATH_NOHUP" "$PATH_ERR"
}

# ===================== systemd服务创建/删除（原版增强） =====================
create_service() {
    ensure_runtime_files
    # 新版systemd服务文件（融合install.sh日志输出）
    cat > /lib/systemd/system/${serviceName}.service << EOT
[Unit]
Description=${APP_NAME}
After=network-online.target
Wants=network-online.target
[Service]
Type=simple
WorkingDirectory=${installPath}
Environment=HOME=${installPath}
ExecStart=/bin/sh -c 'exec "${installPath}/${serviceName}" >> "${PATH_NOHUP}" 2>> "${PATH_ERR}"' sh
SyslogIdentifier=${serviceName}
StandardOutput=syslog
Restart=always
RestartSec=3
TimeoutSec=300
LimitCORE=infinity
LimitNOFILE=1048576
LimitNPROC=655360
[Install]
WantedBy=multi-user.target
EOT
    # rsyslog日志（原版保留）
    touch /var/log/${serviceName}.log
    touch /var/log/hhminer.log
    cat > /etc/rsyslog.d/${serviceName}.conf << EOT
if \$programname == '${serviceName}' then /var/log/${serviceName}.log
& stop
EOT
    systemctl restart rsyslog > /dev/null 2>&1 &
    systemctl daemon-reload
    systemctl enable ${serviceName}
}

remove_service_file() {
    if is_systemd_available; then
        systemctl disable --now "${serviceName}.service" >/dev/null 2>&1
        rm -f -- "/lib/systemd/system/${serviceName}.service"
        rm -f -- "/usr/lib/systemd/system/${serviceName}.service"
        rm -f -- "/etc/rsyslog.d/${serviceName}.conf"
        systemctl restart rsyslog > /dev/null 2>&1 &
        systemctl daemon-reload
    else
        sed -i "/${serviceName}/d" /etc/rc.local 2>/dev/null || true
    fi
}

# ===================== 启停/重启核心 =====================
start() {
    echo -e "[${yellow}操作${plain}] 启动$serviceName代理程序"
    check_process
    if [ $? -eq 0 ]; then
        echo -e "[${yellow}提示${plain}] 程序已在运行，无需重复启动"
        return
    fi
    ensure_runtime_files
    create_service
    systemctl start "${serviceName}.service"
    if wait_for_process_started 10; then
        clear
        port=$(getConfig "START_PORT")
        https=$(getConfig "ENABLE_WEB_TLS")
        web_ui=$(getConfig "ENABLE_WEB_UI")
        ip=$(get_ip)
        echo ""
        echo -e "|----------------------------------------------------------------|"
        echo -e "           ${green}程序启动成功${plain}, 版本: ${bold}${blue}${VERSION}${plain}          "
        echo -e ""
        if [ "$web_ui" = "1" ];then
            if [ "$https" = 0 ];then
                echo -e "WEB访问地址:     ${green}http://${ip}:${port}${plain}"
                echo -e "[${yellow}提示${plain}] 当前HTTP模式，请勿用https访问"
            else
                echo -e "WEB访问地址:     ${green}https://${ip}:${port}${plain}"
                echo -e "[${yellow}提示${plain}] 当前HTTPS模式，请勿用http访问"
            fi
            echo -e "默认账号: admin"
            echo -e "默认密码: 1122345"
            echo -e ""
            echo -e "[${yellow}安全提示${plain}] 服务器/服务商防火墙务必放行${port}端口，登录后修改默认密码与端口"
        else
            echo -e "[${yellow}提示${plain}] WEB面板已关闭，仅可通过hhminerctl CLI工具管理"
        fi
        echo "|----------------------------------------------------------------|"
    else
        echo -e "[${red}错误${plain}] 程序启动失败，请查看错误日志(菜单10)"
    fi
}

stop() {
    echo -e "[${yellow}操作${plain}] 停止$serviceName进程"
    if is_systemd_available && [ -f "/lib/systemd/system/${serviceName}.service" ]; then
        systemctl stop "${serviceName}.service"
    fi
    if check_process; then
        kill_process
    else
